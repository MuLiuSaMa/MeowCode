/** 用户可见回复的语色；默认「普通」不改变任何提示词。 */
export type SpeechStyle = "normal" | "tafei" | "dazui";

export function isSpeechStyle(value: unknown): value is SpeechStyle {
  return value === "normal" || value === "tafei" || value === "dazui";
}

export function normalizeSpeechStyle(value: unknown): SpeechStyle {
  return isSpeechStyle(value) ? value : "normal";
}

